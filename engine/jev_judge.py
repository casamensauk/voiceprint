"""Detection questions put to Jev. Jev judges; it never writes text."""

from __future__ import annotations

from typing import Any

from .jev_client import evaluate, noul

DETECTION_QUESTIONS: dict[str, dict[str, Any]] = {
    "model_written": noul(
        "Read the text in the state. Decide whether it was written by an AI language model "
        "rather than by a person typing in their own words.",
        true="Generated by an AI language model: polished, even, generic phrasing, stock transitions, "
        "tidy structure, little personal detail or idiosyncrasy.",
        false="Written by a person: uneven rhythm, specific personal detail, quirks, opinions, "
        "informal slips or habits an AI would not normally produce.",
    ),
    "paraphrased": noul(
        "Read the text in the state. Decide whether it reads like AI-written text that was then "
        "reworded or 'humanized' to hide where it came from.",
        true="Reworded AI text: synonym swaps, awkward or choppy phrasing, odd word choices, "
        "broken flow, or forced casual touches layered over an AI-style structure.",
        false="Not reworded: the phrasing is either natural human writing or untouched model output.",
    ),
}


def judge_detection(text: str, settings: dict[str, str] | None = None, override_key: str = "") -> dict[str, Any]:
    res = evaluate(text, DETECTION_QUESTIONS, settings=settings, override_key=override_key)
    answers = res["answers"]

    def prob(name: str) -> float:
        a = answers.get(name)
        return float(a.get("noul", 0.0)) if isinstance(a, dict) else 0.0

    return {
        "model_written": prob("model_written"),
        "paraphrased": prob("paraphrased"),
        "usage": res["usage"],
        "cost_usd": res["cost_usd"],
        "model": res["model"],
    }
